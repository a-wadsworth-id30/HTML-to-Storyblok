import path from 'node:path';
import { createPlatformReadiness } from './platform-readiness.js';
import { wireRepositoryRoutes } from './route-handoff.js';
import { ensureArray, pathExists, readJson } from './utils.js';

const AUTOMATIC_FRAMEWORKS = new Set(['astro', 'next', 'nuxt']);

export async function createRouteHandoffChecklist(manifest, {
  repoPath = process.cwd(),
  route = null
} = {}) {
  const root = path.resolve(repoPath);
  const adapterPath = `${manifest.repository_namespace}/adapter-plan.json`;
  const adapterAbsolutePath = path.join(root, adapterPath);
  const adapterPlan = await readAdapterPlan(adapterAbsolutePath);
  const platformReadiness = await createPlatformReadiness(manifest, {
    repoPath: root,
    route,
    adapterPlan
  });
  const routeHandoffPreview = adapterPlan
    ? await wireRepositoryRoutes(manifest, { repoPath: root, route, dryRun: true })
    : null;
  const routes = buildRouteChecklists({
    manifest,
    platformReadiness,
    routeHandoffPreview,
    adapterPlan
  });
  const summary = summarizeChecklist({ adapterPlan, platformReadiness, routeHandoffPreview, routes });
  return {
    action: 'route_handoff_checklist',
    status: summary.status,
    integration_id: manifest.integration_id,
    repository_path: root,
    repository_namespace: manifest.repository_namespace,
    framework: platformReadiness.framework,
    adapter_plan_path: adapterPath,
    automatic_route_handoff_supported: platformReadiness.automatic_route_handoff_supported,
    manual_route_handoff_required: platformReadiness.manual_route_handoff_required,
    summary,
    platform_readiness: summarizePlatformReadiness(platformReadiness),
    route_handoff_preview: summarizeRouteHandoffPreview(routeHandoffPreview),
    routes,
    acceptance_criteria: acceptanceCriteria(platformReadiness.framework),
    safety_policy: {
      additive_only: true,
      host_routes_modified: false,
      host_registries_modified: false,
      production_content_modified: false
    },
    next_steps: nextSteps({ platformReadiness, routeHandoffPreview, routes, manifest, root })
  };
}

export function renderRouteHandoffChecklistMarkdown(checklist) {
  return `# Route Handoff Checklist

Generated by HTML-to-Storyblok.

## Summary

- Status: ${checklist.status}
- Integration: ${checklist.integration_id || 'unknown'}
- Repository: ${checklist.repository_path || 'unknown'}
- Framework: ${checklist.framework || 'unknown'}
- Automatic route handoff supported: ${checklist.automatic_route_handoff_supported ? 'yes' : 'no'}
- Manual route handoff required: ${checklist.manual_route_handoff_required ? 'yes' : 'no'}
- Routes: ${checklist.summary.routes}
- Ready routes: ${checklist.summary.ready_routes}
- Manual routes: ${checklist.summary.manual_routes}
- Blocked routes: ${checklist.summary.blocked_routes}

## Route Checklists

${ensureArray(checklist.routes).map(renderRouteChecklist).join('\n\n') || '- No route checklist entries were generated.'}

## Acceptance Criteria

${ensureArray(checklist.acceptance_criteria).map((item) => `- ${item}`).join('\n')}

## Next Steps

${ensureArray(checklist.next_steps).map((step) => `- ${step}`).join('\n') || '- No next steps recorded.'}
`;
}

async function readAdapterPlan(filePath) {
  if (!(await pathExists(filePath))) return null;
  return readJson(filePath);
}

function buildRouteChecklists({ manifest, platformReadiness, routeHandoffPreview, adapterPlan }) {
  const handoffBySlug = new Map(ensureArray(routeHandoffPreview?.routes).map((entry) => [entry.slug, entry]));
  const adapterRoutesBySlug = new Map(ensureArray(adapterPlan?.routes).map((entry) => [entry.slug, entry]));
  return ensureArray(platformReadiness.routes).map((route) => {
    const handoff = handoffBySlug.get(route.slug) || {};
    const adapterRoute = adapterRoutesBySlug.get(route.slug) || {};
    const automatic = AUTOMATIC_FRAMEWORKS.has(platformReadiness.framework);
    const blocked = route.route_collision_status === 'blocked' ||
      route.route_collision_status === 'failed' ||
      handoff.status === 'blocked' ||
      !route.preview_file_exists ||
      !route.route_proposal_file_exists;
    const manual = !automatic || Boolean(handoff.manual_handoff);
    const status = blocked ? 'blocked' : manual ? 'manual_required' : 'ready';
    return {
      slug: route.slug,
      status,
      suggested_site_path: route.suggested_site_path,
      storyblok_slug: route.storyblok_slug,
      preview_file: route.preview_file,
      preview_file_exists: route.preview_file_exists,
      route_proposal_file: route.route_proposal_file,
      route_proposal_file_exists: route.route_proposal_file_exists,
      suggested_host_files: route.suggested_host_files || adapterRoute.suggested_host_files || [],
      host_route_file: handoff.host_route_file || null,
      handoff_mode: manual ? 'manual_host_router' : 'automatic_route_file',
      blockers: routeBlockers(route, handoff),
      warnings: routeWarnings(route, handoff),
      checklist: routeChecklistItems({
        framework: platformReadiness.framework,
        route,
        handoff,
        automatic,
        blocked,
        manual,
        manifest
      })
    };
  });
}

function routeChecklistItems({ framework, route, handoff, automatic, blocked, manual, manifest }) {
  const items = [];
  items.push(checkItem('Review generated route proposal wrapper', route.route_proposal_file_exists, route.route_proposal_file || 'No route proposal file recorded.'));
  items.push(checkItem('Confirm generated route preview exists', route.preview_file_exists, route.preview_file || 'No route preview file recorded.'));
  items.push(checkItem('Confirm Storyblok draft slug', Boolean(route.storyblok_slug), route.storyblok_slug || `${manifest.integration_id}/${route.slug}`));
  items.push(checkItem('Review route collision analysis', !blocked, route.route_collision_status || handoff.route_collision?.status || 'not_run'));
  if (automatic) {
    items.push(checkItem('Run wire-routes dry run', handoff.status === 'would_create' || handoff.status === 'created', handoff.reason || 'Expected status is would_create before real route wiring.'));
    items.push(checkItem('Create only missing host route file', handoff.status === 'created', handoff.host_route_file || handoff.host_route_file === null ? handoff.host_route_file || 'Run wire-routes without --dry-run after approval.' : 'No host route file recorded.'));
  } else {
    for (const item of manualFrameworkChecklist(framework, route)) {
      items.push(checkItem(item.label, false, item.detail, 'manual'));
    }
  }
  if (manual) {
    items.push(checkItem('Record manual router review evidence', false, 'Attach the host router diff or review note before client handoff.', 'manual'));
  }
  items.push(checkItem('Configure Storyblok Content API runtime token', false, 'Use STORYBLOK_PREVIEW_TOKEN, STORYBLOK_PUBLIC_TOKEN, or STORYBLOK_DELIVERY_TOKEN. Never expose a Management API token.', 'manual'));
  items.push(checkItem('Run host build and browser smoke test', false, `Expected route path: ${route.suggested_site_path || `/${route.slug}`}. Confirm Storyblok source markers when live draft content is expected.`, 'manual'));
  return items;
}

function manualFrameworkChecklist(framework, route) {
  const importTarget = route.route_proposal_file || 'the generated route proposal wrapper';
  if (framework === 'react') {
    return [
      {
        label: 'Choose the host React routing layer',
        detail: 'React Router, file-based routing, or a custom app shell must be selected by the client project owner.'
      },
      {
        label: 'Import the route proposal from the selected React route',
        detail: `Import ${importTarget} and render it with live Storyblok story or blok props.`
      }
    ];
  }
  if (framework === 'vue') {
    return [
      {
        label: 'Choose the host Vue routing layer',
        detail: 'Vue Router, file-based routing, or a custom app shell must be selected by the client project owner.'
      },
      {
        label: 'Import the route proposal from the selected Vue route',
        detail: `Import ${importTarget} and pass live Storyblok story or blok data into the wrapper.`
      }
    ];
  }
  return [
    {
      label: 'Choose the static publishing convention',
      detail: 'Confirm whether this route should become an HTML file, framework route wrapper, or deployment rewrite.'
    },
    {
      label: 'Render the generated HTML module from host code',
      detail: `Use ${importTarget} or the generated template HTML module from the host route shell.`
    }
  ];
}

function checkItem(label, done, detail, owner = 'html-to-storyblok') {
  return {
    label,
    status: done ? 'done' : owner === 'manual' ? 'manual' : 'pending',
    owner,
    detail
  };
}

function routeBlockers(route, handoff) {
  const blockers = [];
  if (!route.preview_file_exists) blockers.push('route_preview_file_missing');
  if (!route.route_proposal_file_exists) blockers.push('route_proposal_file_missing');
  if (route.route_collision_status === 'blocked' || route.route_collision_status === 'failed') blockers.push('route_collision_blocked');
  ensureArray(route.route_collision_blockers).forEach((blocker) => blockers.push(blocker));
  if (handoff.status === 'blocked') blockers.push(handoff.reason || 'route_handoff_blocked');
  return [...new Set(blockers)];
}

function routeWarnings(route, handoff) {
  const warnings = [];
  if (route.route_collision_status === 'warning') warnings.push('route_collision_warning');
  ensureArray(route.route_collision_warnings).forEach((warning) => warnings.push(warning));
  if (handoff.status === 'skipped') warnings.push(handoff.reason || 'route_handoff_skipped');
  return [...new Set(warnings)];
}

function summarizeChecklist({ adapterPlan, platformReadiness, routeHandoffPreview, routes }) {
  const blockedRoutes = routes.filter((route) => route.status === 'blocked').length;
  const manualRoutes = routes.filter((route) => route.status === 'manual_required').length;
  const warningRoutes = routes.filter((route) => route.warnings.length > 0).length;
  const status = !adapterPlan || platformReadiness.status === 'blocked' || platformReadiness.status === 'failed' || blockedRoutes > 0
    ? 'blocked'
    : manualRoutes > 0
      ? 'manual_required'
      : routeHandoffPreview?.status === 'warning' || warningRoutes > 0
        ? 'warning'
        : 'ready';
  return {
    status,
    adapter_plan_available: Boolean(adapterPlan),
    platform_readiness_status: platformReadiness.status,
    route_handoff_preview_status: routeHandoffPreview?.status || 'not_run',
    routes: routes.length,
    ready_routes: routes.filter((route) => route.status === 'ready').length,
    manual_routes: manualRoutes,
    blocked_routes: blockedRoutes,
    warning_routes: warningRoutes,
    checklist_items: routes.reduce((total, route) => total + route.checklist.length, 0),
    manual_checklist_items: routes.reduce((total, route) => total + route.checklist.filter((item) => item.status === 'manual').length, 0)
  };
}

function summarizePlatformReadiness(readiness) {
  return {
    status: readiness.status,
    framework: readiness.framework,
    failed_checks: readiness.summary?.failed_checks || 0,
    warning_checks: readiness.summary?.warning_checks || 0,
    routes: readiness.summary?.routes || 0,
    markdown_report: readiness.markdown_report || null
  };
}

function summarizeRouteHandoffPreview(preview) {
  if (!preview) return null;
  return {
    status: preview.status,
    dry_run: Boolean(preview.dry_run),
    routes: preview.summary?.total || ensureArray(preview.routes).length,
    would_create: preview.summary?.would_create || 0,
    blocked: preview.summary?.blocked || 0,
    skipped: preview.summary?.skipped || 0,
    manual_handoff: preview.summary?.manual_handoff || 0,
    markdown_report: preview.markdown_report || null
  };
}

function acceptanceCriteria(framework) {
  const shared = [
    'Generated integration files remain under the integration namespace.',
    'No existing host route, router registry, dependency file, Storyblok production story, or published content is modified.',
    'Imported route renders the expected Storyblok draft slug or clearly marked generated fallback.',
    'Host lint/typecheck/build and browser smoke checks are recorded before client handoff.',
    'Runtime uses a Storyblok Content API token only; Management API tokens are not deployed.'
  ];
  if (AUTOMATIC_FRAMEWORKS.has(framework)) {
    return [
      ...shared,
      'wire-routes dry run reports would_create for every approved route before the real route file is created.',
      'Real wire-routes creates only missing host route files and refuses collisions.'
    ];
  }
  return [
    ...shared,
    'Manual router registration is reviewed by the project owner.',
    'Manual route diff references generated route proposal wrappers rather than raw template files.'
  ];
}

function nextSteps({ platformReadiness, routeHandoffPreview, routes, manifest, root }) {
  const manifestPath = '.tmp/html-to-storyblok/integration-manifest.json';
  const steps = [];
  if (platformReadiness.status === 'blocked' || platformReadiness.status === 'failed') {
    steps.push(`Run html-to-storyblok platform-readiness --manifest ${manifestPath} --repo ${root} and resolve blockers.`);
  }
  if (routeHandoffPreview?.status === 'blocked') {
    steps.push(`Run html-to-storyblok route-collisions --manifest ${manifestPath} --repo ${root} and resolve route blockers.`);
  }
  if (routes.some((route) => route.status === 'manual_required')) {
    steps.push('Review the manual route checklist with the client project owner and record the host router diff or approval note.');
  }
  if (AUTOMATIC_FRAMEWORKS.has(platformReadiness.framework) && routes.some((route) => route.status === 'ready')) {
    steps.push(`Run html-to-storyblok wire-routes --manifest ${manifestPath} --repo ${root} --dry-run, then run without --dry-run only after review.`);
  }
  steps.push(`Run html-to-storyblok evidence-index --manifest ${manifestPath} --repo ${root} after route handoff evidence is recorded.`);
  steps.push(`Run deployed preview smoke checks for ${manifest.integration_id || '<integration-id>'} before final sign-off.`);
  return [...new Set(steps)];
}

function renderRouteChecklist(route) {
  return `### ${route.suggested_site_path || route.slug}

- Status: ${route.status}
- Storyblok slug: ${route.storyblok_slug || 'unknown'}
- Preview file: ${route.preview_file_exists ? 'available' : 'missing'}${route.preview_file ? ` - \`${route.preview_file}\`` : ''}
- Route proposal: ${route.route_proposal_file_exists ? 'available' : 'missing'}${route.route_proposal_file ? ` - \`${route.route_proposal_file}\`` : ''}
- Suggested host files: ${ensureArray(route.suggested_host_files).map((file) => `\`${file}\``).join(', ') || 'none'}
- Host route file: ${route.host_route_file || 'not created'}
- Handoff mode: ${route.handoff_mode}
- Blockers: ${route.blockers.length ? route.blockers.join(', ') : 'none'}
- Warnings: ${route.warnings.length ? route.warnings.join(', ') : 'none'}

${route.checklist.map((item) => `- [${item.status === 'done' ? 'x' : ' '}] ${item.label}: ${item.detail}`).join('\n')}`;
}
