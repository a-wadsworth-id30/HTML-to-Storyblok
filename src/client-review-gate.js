import path from 'node:path';
import { inspectRepository } from './inspectors.js';
import { wireRepositoryRoutes } from './route-handoff.js';
import { diffIntegration, preflightRepositoryIntegration, runRepositoryScript } from './validator.js';
import { ensureArray, pathExists } from './utils.js';

const DEFAULT_HOST_CHECKS = ['lint', 'typecheck', 'build'];

export async function createClientApplyReviewGate(manifest, {
  repoPath = process.cwd(),
  mode = 'apply',
  repositoryPreflight = null,
  hostChecks = DEFAULT_HOST_CHECKS,
  skipHostChecks = false
} = {}) {
  const root = path.resolve(repoPath);
  const startedAt = new Date().toISOString();
  const checks = [];
  const repository = await safeInspectRepository(root);
  const preflight = repositoryPreflight || await preflightRepositoryIntegration(manifest, { repoPath: root, mode });
  const diff = await safeDiffIntegration(manifest, root);
  const routeHandoff = await safeRouteHandoffPreview(manifest, root);
  const hostScripts = skipHostChecks
    ? hostChecks.map((script) => ({
      action: 'run_repository_script',
      dry_run: true,
      script,
      status: 'skipped',
      reason: 'host checks were skipped by --skip-host-checks.'
    }))
    : await Promise.all(hostChecks.map((script) => safeRunRepositoryScript(root, script)));

  addCheck(
    checks,
    'repository_preflight',
    preflight.status === 'passed' ? 'passed' : 'failed',
    preflight.status === 'passed'
      ? 'Repository preflight is safe for additive integration output.'
      : 'Repository preflight found blocking issues before generated files can be written.',
    failedCheckNames(preflight)
  );
  addCheck(
    checks,
    'planned_writes_isolated',
    plannedWritesAreIsolated(manifest, diff) ? 'passed' : 'failed',
    plannedWritesAreIsolated(manifest, diff)
      ? 'All planned repository writes stay inside the integration namespace or public integration asset namespace.'
      : 'One or more planned repository writes escape the integration namespace.',
    plannedWriteSummary(manifest, diff)
  );
  addCheck(
    checks,
    'host_routes_preserved',
    hostRoutesPreserved(manifest) ? 'passed' : 'failed',
    hostRoutesPreserved(manifest)
      ? 'The apply plan does not modify host route files or router registries.'
      : 'The apply plan attempts to modify host routes or router registries.',
    {
      files_to_modify: ensureArray(manifest.repository?.files_to_modify).length,
      host_routes_modified: Boolean(manifest.repository?.host_routes_modified || manifest.repository?.host_registries_modified)
    }
  );
  addCheck(
    checks,
    'route_handoff_review',
    routeHandoffCheckStatus(routeHandoff),
    routeHandoffMessage(routeHandoff),
    routeHandoffDetails(routeHandoff)
  );
  addCheck(
    checks,
    'host_script_discovery',
    hostScriptDiscoveryStatus(hostScripts, skipHostChecks),
    hostScriptDiscoveryMessage(hostScripts, skipHostChecks),
    hostScripts.map((script) => ({
      script: script.script,
      status: script.status || (script.command ? 'available' : 'unavailable'),
      command: script.command || null,
      reason: script.reason || null
    }))
  );

  const summary = summarizeGate(checks);
  return {
    action: 'client_apply_review_gate',
    status: summary.status,
    mode,
    started_at: startedAt,
    finished_at: new Date().toISOString(),
    integration_id: manifest.integration_id,
    repository_path: root,
    repository_namespace: manifest.repository_namespace,
    framework: repository.framework?.name || manifest.template?.framework || 'unknown',
    package_manager: repository.package_manager || 'unknown',
    checks,
    failed_checks: summary.failed,
    warning_checks: summary.warnings,
    ready_for_apply: summary.failed === 0,
    ready_for_route_handoff: routeHandoff?.status === 'passed',
    repository,
    preflight,
    diff,
    route_handoff_preview: routeHandoff,
    host_scripts: hostScripts,
    next_steps: nextSteps({ summary, routeHandoff, hostScripts })
  };
}

export function renderClientApplyReviewGateMarkdown(gate) {
  const checks = ensureArray(gate.checks);
  const planned = plannedCounts(gate.diff);
  const hostScripts = ensureArray(gate.host_scripts);
  const routeHandoff = gate.route_handoff_preview || {};
  return `# Client Apply Review Gate

Generated by HTML-to-Storyblok.

## Summary

- Status: ${gate.status || 'recorded'}
- Ready for apply: ${gate.ready_for_apply ? 'yes' : 'no'}
- Ready for route handoff: ${gate.ready_for_route_handoff ? 'yes' : 'no'}
- Integration: ${gate.integration_id || 'unknown'}
- Repository: ${gate.repository_path || 'unknown'}
- Namespace: ${gate.repository_namespace || 'unknown'}
- Framework: ${gate.framework || 'unknown'}
- Package manager: ${gate.package_manager || 'unknown'}

## Checks

${checks.map((check) => `- ${check.status}: ${check.name} - ${check.message}`).join('\n') || '- No checks recorded.'}

## Planned Repository Writes

- Text files: ${planned.files}
- Assets: ${planned.assets}
- Existing planned targets: ${planned.existing}
- Missing planned targets: ${planned.missing}
- Host routes modified by apply: ${gate.diff?.host_routes_modified ? 'yes' : 'no'}

## Route Handoff Preview

- Status: ${routeHandoff.status || 'not_run'}
- Routes checked: ${ensureArray(routeHandoff.routes).length}
- Would create: ${routeHandoff.summary?.would_create || 0}
- Blocked: ${routeHandoff.summary?.blocked || 0}
- Manual handoff routes: ${routeHandoff.summary?.manual_handoff || routeHandoff.manual_handoff?.routes || 0}
${routeHandoff.reason ? `- Reason: ${routeHandoff.reason}\n` : ''}
## Host Script Discovery

${hostScripts.map((script) => `- ${script.script}: ${script.command || script.status || 'unavailable'}${script.reason ? ` (${script.reason})` : ''}`).join('\n') || '- No host scripts checked.'}

## Next Steps

${ensureArray(gate.next_steps).map((step) => `- ${step}`).join('\n') || '- No next steps recorded.'}
`;
}

async function safeInspectRepository(root) {
  try {
    return await inspectRepository(root);
  } catch (error) {
    return {
      action: 'inspect_repository',
      status: 'failed',
      repository_path: root,
      error: error.message || String(error),
      framework: { name: 'unknown' },
      package_manager: 'unknown'
    };
  }
}

async function safeDiffIntegration(manifest, root) {
  try {
    return await diffIntegration(manifest, { repoPath: root });
  } catch (error) {
    return {
      action: 'diff_manifest',
      status: 'failed',
      error: error.message || String(error),
      repository_files: [],
      repository_assets: []
    };
  }
}

async function safeRouteHandoffPreview(manifest, root) {
  const adapterPath = path.join(root, manifest.repository_namespace || '', 'adapter-plan.json');
  if (!(await pathExists(adapterPath))) {
    return {
      action: 'wire_repository_routes',
      status: 'not_ready',
      dry_run: true,
      reason: 'Generated adapter plan is not available yet. Run apply --dry-run or generate to create route proposal evidence.',
      routes: [],
      summary: {
        total: 0,
        created: 0,
        would_create: 0,
        blocked: 0,
        skipped: 0,
        manual_handoff: 0
      }
    };
  }
  return wireRepositoryRoutes(manifest, { repoPath: root, dryRun: true });
}

async function safeRunRepositoryScript(root, script) {
  try {
    return await runRepositoryScript({ repoPath: root, script, dryRun: true });
  } catch (error) {
    return {
      action: 'run_repository_script',
      dry_run: true,
      script,
      status: 'unavailable',
      reason: error.message || String(error)
    };
  }
}

function failedCheckNames(preflight) {
  return ensureArray(preflight?.checks)
    .filter((check) => check.status === 'failed')
    .map((check) => check.name);
}

function plannedWritesAreIsolated(manifest, diff) {
  const namespace = normalizePath(manifest.repository_namespace);
  const publicNamespace = `public/integrations/${manifest.integration_id}`;
  const targets = [
    ...ensureArray(diff?.repository_files).map((entry) => entry.path),
    ...ensureArray(diff?.repository_assets).map((entry) => entry.path)
  ].filter(Boolean);
  return targets.every((target) => isSameOrChildPath(target, namespace) || isSameOrChildPath(target, publicNamespace));
}

function plannedWriteSummary(manifest, diff) {
  const targets = [
    ...ensureArray(diff?.repository_files).map((entry) => ({ type: 'file', path: entry.path, status: entry.status })),
    ...ensureArray(diff?.repository_assets).map((entry) => ({ type: 'asset', path: entry.path, status: entry.status }))
  ];
  return {
    namespace: manifest.repository_namespace,
    public_asset_namespace: `public/integrations/${manifest.integration_id}`,
    targets: targets.slice(0, 50),
    omitted_targets: Math.max(0, targets.length - 50)
  };
}

function hostRoutesPreserved(manifest) {
  return ensureArray(manifest.repository?.files_to_modify).length === 0 &&
    !manifest.repository?.host_routes_modified &&
    !manifest.repository?.host_registries_modified;
}

function routeHandoffCheckStatus(routeHandoff) {
  if (!routeHandoff || routeHandoff.status === 'not_ready') return 'warning';
  if (routeHandoff.status === 'failed') return 'failed';
  if (routeHandoff.status === 'blocked') return 'warning';
  return 'passed';
}

function routeHandoffMessage(routeHandoff) {
  if (!routeHandoff || routeHandoff.status === 'not_ready') {
    return 'Route proposal evidence is not generated yet; apply still remains isolated and does not modify host routes.';
  }
  if (routeHandoff.status === 'blocked') {
    return 'Automatic route handoff has blockers and needs manual review before exposing imported routes.';
  }
  if (routeHandoff.status === 'failed') return 'Route handoff preview failed.';
  if (routeHandoff.status === 'skipped') return 'Route handoff is manual for this framework.';
  return 'Route handoff preview is available and additive-only.';
}

function routeHandoffDetails(routeHandoff) {
  return {
    status: routeHandoff?.status || 'not_run',
    routes: ensureArray(routeHandoff?.routes).length,
    would_create: routeHandoff?.summary?.would_create || 0,
    blocked: routeHandoff?.summary?.blocked || 0,
    manual_handoff: routeHandoff?.summary?.manual_handoff || routeHandoff?.manual_handoff?.routes || 0,
    reason: routeHandoff?.reason || null
  };
}

function hostScriptDiscoveryStatus(hostScripts, skipHostChecks) {
  if (skipHostChecks) return 'warning';
  if (hostScripts.some((script) => script.command)) return 'passed';
  return 'warning';
}

function hostScriptDiscoveryMessage(hostScripts, skipHostChecks) {
  if (skipHostChecks) return 'Host checks were explicitly skipped; run equivalent client repository checks before handoff.';
  const available = hostScripts.filter((script) => script.command).map((script) => script.script);
  if (available.length > 0) return `Available host check script(s): ${available.join(', ')}.`;
  return 'No standard host check scripts were detected. Run the client repository checks manually before handoff.';
}

function summarizeGate(checks) {
  const failed = checks.filter((check) => check.status === 'failed').length;
  const warnings = checks.filter((check) => check.status === 'warning').length;
  return {
    failed,
    warnings,
    status: failed > 0 ? 'failed' : warnings > 0 ? 'warning' : 'passed'
  };
}

function nextSteps({ summary, routeHandoff, hostScripts }) {
  const steps = [];
  if (summary.failed > 0) {
    steps.push('Resolve failed client review checks before running a real repository apply.');
  }
  if (!hostScripts.some((script) => script.command)) {
    steps.push('Identify the client repository lint, typecheck, build, and browser smoke commands before handoff.');
  }
  if (!routeHandoff || ['not_ready', 'blocked'].includes(routeHandoff.status)) {
    steps.push('Run apply --dry-run or generate, then review route proposals with wire-routes --dry-run before exposing imported pages.');
  }
  steps.push('Keep generated files inside the integration namespace until a human reviews route handoff evidence.');
  steps.push('Use rollback-preview before any cleanup; rollback remains explicit and integration-ID gated.');
  return steps;
}

function plannedCounts(diff) {
  const repositoryFiles = ensureArray(diff?.repository_files);
  const repositoryAssets = ensureArray(diff?.repository_assets);
  const targets = [...repositoryFiles, ...repositoryAssets];
  return {
    files: repositoryFiles.length,
    assets: repositoryAssets.length,
    existing: targets.filter((entry) => entry.status === 'exists').length,
    missing: targets.filter((entry) => entry.status === 'missing').length
  };
}

function addCheck(checks, name, status, message, details = null) {
  checks.push({ name, status, message, details });
}

function isSameOrChildPath(file, parent) {
  const normalizedFile = normalizePath(file);
  const normalizedParent = normalizePath(parent);
  return normalizedFile === normalizedParent || normalizedFile.startsWith(`${normalizedParent}/`);
}

function normalizePath(value) {
  return String(value || '').replaceAll('\\', '/').replace(/^\/+|\/+$/g, '');
}
