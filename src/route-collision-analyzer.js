import { readdir, readFile } from 'node:fs/promises';
import path from 'node:path';
import { ensureArray, pathExists, readJson, unique } from './utils.js';

const ROUTE_EXTENSIONS = new Set(['.astro', '.js', '.jsx', '.ts', '.tsx', '.vue', '.md', '.mdx', '.html']);
const ROUTE_SCAN_DIRS = ['src/pages', 'src/app', 'pages', 'app'];
const SKIP_DIRS = new Set(['node_modules', '.git', '.next', '.nuxt', '.output', 'dist', 'build', '.netlify']);
const SUPPORTED_HOST_TARGETS = new Set(['astro', 'next', 'nuxt']);

export async function analyzeRouteCollisions(manifest, {
  repoPath = process.cwd(),
  adapterPlan = null,
  route = null
} = {}) {
  const root = path.resolve(repoPath);
  const adapterPath = `${manifest.repository_namespace}/adapter-plan.json`;
  const adapter = adapterPlan || await readAdapterPlan(root, adapterPath);
  if (!adapter) {
    return {
      action: 'analyze_route_collisions',
      status: 'blocked',
      repository_path: root,
      integration_id: manifest.integration_id || null,
      policy: 'read-only-route-collision-analysis',
      reason: `Generated adapter plan not found: ${adapterPath}. Run generate or apply before analyzing route collisions.`,
      routes: [],
      existing_routes: [],
      rewrites: [],
      summary: emptyRouteCollisionSummary()
    };
  }

  const selectedRoutes = filterRoutes(ensureArray(adapter.routes), route);
  const existingRoutes = await discoverExistingRoutes(root, adapter.framework);
  const rewrites = await discoverNetlifyRewrites(root);
  const duplicatePaths = plannedDuplicateSitePaths(selectedRoutes);
  const analyzedRoutes = selectedRoutes.map((entry) => analyzeRoute({
    manifest,
    adapter,
    route: entry,
    existingRoutes,
    rewrites,
    duplicatePaths
  }));
  const summary = summarizeRouteCollisionAnalysis(analyzedRoutes, existingRoutes, rewrites);
  const status = summary.blocked > 0 ? 'blocked' : summary.warnings > 0 ? 'warning' : 'passed';

  return {
    action: 'analyze_route_collisions',
    status,
    repository_path: root,
    integration_id: manifest.integration_id || adapter.integration_id || null,
    framework: adapter.framework || 'unknown',
    policy: 'read-only-route-collision-analysis',
    adapter_plan: adapterPath,
    routes: analyzedRoutes,
    existing_routes: existingRoutes.slice(0, 100),
    rewrites,
    summary,
    warnings: routeCollisionWarnings(summary)
  };
}

export function renderRouteCollisionReport(result) {
  const routes = ensureArray(result.routes);
  const rewriteRows = ensureArray(result.rewrites).slice(0, 20)
    .map((rewrite) => `- ${rewrite.source}: ${rewrite.to || 'no target'} (${rewrite.source_file})`)
    .join('\n') || '- None detected';
  return `# Route Collision And Rewrite Analysis

Generated by HTML-to-Storyblok.

## Summary

- Status: ${result.status || 'recorded'}
- Policy: ${result.policy || 'read-only-route-collision-analysis'}
- Framework: ${result.framework || 'unknown'}
- Routes checked: ${result.summary?.routes || routes.length}
- Clear: ${result.summary?.clear || 0}
- Blocked: ${result.summary?.blocked || 0}
- Warnings: ${result.summary?.warnings || 0}
- Existing route files scanned: ${result.summary?.existing_route_files || 0}
- Rewrite rules scanned: ${result.summary?.rewrite_rules || 0}
${result.reason ? `- Reason: ${result.reason}\n` : ''}
## Route Evidence

${routes.length ? routes.map(renderRouteCollisionEvidence).join('\n\n') : '- No routes were checked.'}

## Netlify Rewrites And Redirects

${rewriteRows}

## Required Checks

- Resolve every blocked route before running \`wire-routes\` without \`--dry-run\`.
- Review warning-level rewrite overlaps because deployed routes may be masked by Netlify routing.
- Run host lint, typecheck, build, and browser smoke checks after route wiring.
`;
}

function analyzeRoute({ manifest, adapter, route, existingRoutes, rewrites, duplicatePaths }) {
  const sitePath = normalizeSitePath(route.suggested_site_path || route.path || route.slug);
  const hostRouteFile = concreteHostRouteFile(adapter.framework, route);
  const exactMatches = existingRoutes.filter((entry) => entry.exact_path === sitePath);
  const dynamicOverlaps = existingRoutes.filter((entry) => entry.dynamic && routePatternMatches(entry, sitePath));
  const rewriteOverlaps = rewrites.filter((entry) => rewriteMatches(entry, sitePath));
  const duplicatePlannedPath = duplicatePaths.has(sitePath);
  const checks = [
    routeCheck('site_path_safe', safeSitePath(sitePath), safeSitePath(sitePath) ? 'Suggested site path is safe.' : `Unsafe suggested site path: ${sitePath}`),
    routeCheck('storyblok_slug_namespaced', String(route.storyblok_slug || '').startsWith(`${manifest.integration_id}/`), 'Storyblok slug remains inside the integration story folder.'),
    routeCheck(
      'host_route_target_safe',
      !hostRouteFile || safeHostRouteTarget(adapter.framework, hostRouteFile),
      hostRouteFile ? `Host route target is scoped to ${hostRouteFile}.` : 'No automatic host route target was selected.'
    ),
    routeCheck(
      'planned_site_path_unique',
      !duplicatePlannedPath,
      duplicatePlannedPath ? `Multiple imported routes target ${sitePath}.` : 'Imported route path is unique within the adapter plan.'
    ),
    routeCheck(
      'existing_route_file_available',
      exactMatches.length === 0,
      exactMatches.length === 0 ? 'No existing host route file owns this path.' : `Existing host route file(s) own ${sitePath}.`,
      exactMatches.map(routeEvidence),
      'failed'
    ),
    routeCheck(
      'dynamic_route_overlap',
      dynamicOverlaps.length === 0,
      dynamicOverlaps.length === 0 ? 'No existing dynamic route pattern overlaps this path.' : `Existing dynamic route pattern(s) may already handle ${sitePath}.`,
      dynamicOverlaps.map(routeEvidence),
      'failed'
    ),
    routeCheck(
      'netlify_rewrite_overlap',
      rewriteOverlaps.length === 0,
      rewriteOverlaps.length === 0 ? 'No Netlify redirect or rewrite overlaps this path.' : `Netlify redirect/rewrite rule(s) may affect ${sitePath}.`,
      rewriteOverlaps.map(rewriteEvidence),
      'warning'
    )
  ];
  const failed = checks.filter((check) => check.status === 'failed');
  const warnings = checks.filter((check) => check.status === 'warning');
  return {
    slug: route.slug || null,
    suggested_site_path: sitePath,
    storyblok_slug: route.storyblok_slug || null,
    route_proposal_file: route.route_proposal_file || route.proposal_file || null,
    host_route_file: hostRouteFile || null,
    status: failed.length > 0 ? 'blocked' : warnings.length > 0 ? 'warning' : 'clear',
    blockers: failed.map((check) => check.name),
    warnings: warnings.map((check) => check.name),
    checks
  };
}

async function readAdapterPlan(root, adapterPath) {
  const fullPath = path.join(root, normalizeRelativePath(adapterPath));
  if (!(await pathExists(fullPath))) return null;
  return readJson(fullPath);
}

async function discoverExistingRoutes(root, framework = 'auto') {
  const routeFiles = [];
  for (const dir of ROUTE_SCAN_DIRS) {
    const absolute = path.join(root, dir);
    if (!(await pathExists(absolute))) continue;
    const files = await walkFiles(absolute, root);
    routeFiles.push(...files);
  }
  return uniqueRouteEntries(routeFiles
    .map((filePath) => routeFileEntry(filePath, framework))
    .filter(Boolean));
}

async function walkFiles(dir, root, files = []) {
  const entries = await readdir(dir, { withFileTypes: true });
  for (const entry of entries) {
    if (SKIP_DIRS.has(entry.name)) continue;
    const absolute = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      await walkFiles(absolute, root, files);
      continue;
    }
    if (!entry.isFile()) continue;
    const ext = path.extname(entry.name);
    if (!ROUTE_EXTENSIONS.has(ext)) continue;
    files.push(path.relative(root, absolute).split(path.sep).join('/'));
  }
  return files;
}

function routeFileEntry(filePath, framework) {
  const normalized = normalizeRelativePath(filePath);
  if (normalized.startsWith('src/pages/')) return routeEntryFromPagesFile(normalized, 'src/pages');
  if (normalized.startsWith('pages/')) return routeEntryFromPagesFile(normalized, 'pages');
  if (normalized.startsWith('src/app/')) return routeEntryFromAppFile(normalized, 'src/app');
  if (normalized.startsWith('app/')) return routeEntryFromAppFile(normalized, 'app');
  if (framework === 'nuxt' && normalized.startsWith('pages/')) return routeEntryFromPagesFile(normalized, 'pages');
  return null;
}

function routeEntryFromPagesFile(filePath, rootDir) {
  const relative = filePath.slice(rootDir.length + 1);
  const parsed = path.posix.parse(relative);
  if (parsed.name.startsWith('_') && rootDir === 'pages' && ['_app', '_document', '_error'].includes(parsed.name)) return null;
  const segments = stripIndexSegment(path.posix.join(parsed.dir, parsed.name).split('/').filter(Boolean));
  return routeEntry(filePath, segments);
}

function routeEntryFromAppFile(filePath, rootDir) {
  const relative = filePath.slice(rootDir.length + 1);
  const parsed = path.posix.parse(relative);
  if (parsed.name !== 'page' && parsed.name !== 'route') return null;
  const segments = parsed.dir.split('/').filter(Boolean)
    .filter((segment) => !segment.startsWith('(') && !segment.startsWith('@'));
  return routeEntry(filePath, segments);
}

function routeEntry(filePath, segments) {
  const dynamic = segments.some(isDynamicRouteSegment);
  const exactPath = dynamic ? null : `/${segments.join('/')}`.replace(/\/+/g, '/') || '/';
  return {
    file_path: filePath,
    exact_path: exactPath === '' ? '/' : exactPath,
    route_pattern: `/${segments.map(patternSegmentLabel).join('/')}`.replace(/\/+/g, '/') || '/',
    dynamic,
    regex: dynamic ? routeRegexFromSegments(segments).source : null
  };
}

function stripIndexSegment(segments) {
  if (segments.at(-1) === 'index') return segments.slice(0, -1);
  return segments;
}

function routePatternMatches(route, sitePath) {
  if (!route.dynamic || !route.regex) return false;
  return new RegExp(route.regex).test(sitePath);
}

function routeRegexFromSegments(segments) {
  if (segments.length === 0) return /^\/$/;
  const parts = segments.map((segment) => {
    if (isCatchAllSegment(segment)) return '(?:/.*)?';
    if (isDynamicRouteSegment(segment)) return '/[^/]+';
    return `/${escapeRegExp(routeStaticSegment(segment))}`;
  });
  return new RegExp(`^${parts.join('')}/?$`);
}

function patternSegmentLabel(segment) {
  if (isCatchAllSegment(segment)) return '*';
  if (isDynamicRouteSegment(segment)) return ':param';
  return routeStaticSegment(segment);
}

function routeStaticSegment(segment) {
  return String(segment).replace(/^\((.*)\)$/, '$1');
}

function isDynamicRouteSegment(segment) {
  return /^\[.*\]$/.test(segment) || /^_/.test(segment);
}

function isCatchAllSegment(segment) {
  return /^\[\.\.\..+\]$/.test(segment) || /^_\.\.\./.test(segment);
}

async function discoverNetlifyRewrites(root) {
  const candidates = [
    '_redirects',
    'public/_redirects',
    'static/_redirects',
    'netlify.toml'
  ];
  const results = [];
  for (const candidate of candidates) {
    const filePath = path.join(root, candidate);
    if (!(await pathExists(filePath))) continue;
    const text = await readFile(filePath, 'utf8');
    if (candidate.endsWith('_redirects')) {
      results.push(...parseRedirectsFile(candidate, text));
    } else {
      results.push(...parseNetlifyToml(candidate, text));
    }
  }
  return results;
}

function parseRedirectsFile(sourceFile, text) {
  return text.split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith('#'))
    .map((line, index) => {
      const [source, to, status] = line.split(/\s+/);
      return rewriteEntry({ source, to, status, sourceFile, line: index + 1 });
    })
    .filter(Boolean);
}

function parseNetlifyToml(sourceFile, text) {
  const entries = [];
  let current = null;
  for (const [index, rawLine] of text.split(/\r?\n/).entries()) {
    const line = rawLine.trim();
    if (line === '[[redirects]]') {
      if (current?.source) entries.push(rewriteEntry({ ...current, sourceFile }));
      current = { line: index + 1 };
      continue;
    }
    if (!current) continue;
    const match = line.match(/^(from|to|status)\s*=\s*"?([^"]+)"?/);
    if (!match) continue;
    const [, key, value] = match;
    current[key === 'from' ? 'source' : key] = value.trim();
  }
  if (current?.source) entries.push(rewriteEntry({ ...current, sourceFile }));
  return entries.filter(Boolean);
}

function rewriteEntry({ source, to = null, status = null, sourceFile, line }) {
  const normalized = normalizeSitePath(source);
  if (!safeSitePath(normalized)) return null;
  const wildcard = /[*:]/.test(normalized);
  return {
    source: normalized,
    to,
    status_code: status ? Number(status) || status : null,
    source_file: sourceFile,
    line,
    wildcard,
    regex: wildcard ? rewriteRegex(normalized).source : null
  };
}

function rewriteMatches(rewrite, sitePath) {
  if (rewrite.source === sitePath) return true;
  if (!rewrite.regex) return false;
  return new RegExp(rewrite.regex).test(sitePath);
}

function rewriteRegex(source) {
  const escaped = source
    .split('*').map(escapeRegExp).join('.*')
    .replace(/:([A-Za-z0-9_]+)/g, '[^/]+');
  return new RegExp(`^${escaped}/?$`);
}

function plannedDuplicateSitePaths(routes) {
  const counts = new Map();
  for (const route of routes) {
    const sitePath = normalizeSitePath(route.suggested_site_path || route.path || route.slug);
    counts.set(sitePath, (counts.get(sitePath) || 0) + 1);
  }
  return new Set([...counts.entries()].filter(([, count]) => count > 1).map(([sitePath]) => sitePath));
}

function summarizeRouteCollisionAnalysis(routes, existingRoutes, rewrites) {
  return {
    routes: routes.length,
    clear: routes.filter((route) => route.status === 'clear').length,
    blocked: routes.filter((route) => route.status === 'blocked').length,
    warnings: routes.reduce((total, route) => total + route.warnings.length, 0),
    existing_route_files: existingRoutes.length,
    exact_route_file_collisions: routes.reduce((total, route) => total + checkDetails(route, 'existing_route_file_available').length, 0),
    dynamic_route_overlaps: routes.reduce((total, route) => total + checkDetails(route, 'dynamic_route_overlap').length, 0),
    rewrite_rules: rewrites.length,
    rewrite_overlaps: routes.reduce((total, route) => total + checkDetails(route, 'netlify_rewrite_overlap').length, 0)
  };
}

function routeCollisionWarnings(summary) {
  const warnings = [];
  if (summary.exact_route_file_collisions > 0) warnings.push(`${summary.exact_route_file_collisions} imported route(s) collide with existing host route files.`);
  if (summary.dynamic_route_overlaps > 0) warnings.push(`${summary.dynamic_route_overlaps} imported route(s) overlap existing dynamic route patterns.`);
  if (summary.rewrite_overlaps > 0) warnings.push(`${summary.rewrite_overlaps} imported route(s) may be affected by Netlify rewrites or redirects.`);
  return warnings;
}

function routeCheck(name, passed, message, details = [], failureStatus = 'failed') {
  return {
    name,
    status: passed ? 'passed' : failureStatus,
    message,
    details: ensureArray(details)
  };
}

function checkDetails(route, checkName) {
  return ensureArray(route.checks.find((check) => check.name === checkName)?.details);
}

function routeEvidence(route) {
  return {
    file_path: route.file_path,
    exact_path: route.exact_path,
    route_pattern: route.route_pattern,
    dynamic: route.dynamic
  };
}

function rewriteEvidence(rewrite) {
  return {
    source: rewrite.source,
    to: rewrite.to,
    source_file: rewrite.source_file,
    line: rewrite.line,
    wildcard: rewrite.wildcard
  };
}

function renderRouteCollisionEvidence(route) {
  const failed = route.checks.filter((check) => check.status === 'failed');
  const warnings = route.checks.filter((check) => check.status === 'warning');
  return `### ${route.suggested_site_path || route.slug || 'route'}

- Status: ${route.status}
- Storyblok draft: ${route.storyblok_slug || 'not supplied'}
- Route proposal: ${route.route_proposal_file || 'not supplied'}
- Suggested host route: ${route.host_route_file || 'manual review'}
- Blockers: ${failed.length ? failed.map((check) => check.name).join(', ') : 'none'}
- Warnings: ${warnings.length ? warnings.map((check) => check.name).join(', ') : 'none'}
${[...failed, ...warnings].map((check) => `- ${check.name}: ${check.message}${check.details.length ? ` (${check.details.map((entry) => entry.file_path || entry.source || entry.route_pattern || JSON.stringify(entry)).join(', ')})` : ''}`).join('\n')}`;
}

function concreteHostRouteFile(framework, route) {
  const candidates = ensureArray(route.suggested_host_files)
    .filter((filePath) => typeof filePath === 'string' && !/review the host router/i.test(filePath));
  if (framework === 'astro') return candidates.find((filePath) => filePath.endsWith('.astro')) || null;
  if (framework === 'next') return candidates.find((filePath) => /\.(jsx|tsx|js|ts)$/.test(filePath)) || null;
  if (framework === 'nuxt') return candidates.find((filePath) => filePath.endsWith('.vue')) || null;
  return null;
}

function safeHostRouteTarget(framework, filePath) {
  const normalized = normalizeRelativePath(filePath);
  if (normalized.startsWith('..') || path.posix.isAbsolute(normalized)) return false;
  if (framework === 'astro') return normalized.startsWith('src/pages/') && normalized.endsWith('.astro');
  if (framework === 'next') return normalized.startsWith('src/app/') && /\.(jsx|tsx|js|ts)$/.test(normalized);
  if (framework === 'nuxt') return normalized.startsWith('pages/') && normalized.endsWith('.vue');
  return !SUPPORTED_HOST_TARGETS.has(framework);
}

function filterRoutes(routes, route) {
  if (!route) return routes;
  const normalized = normalizeRouteSelector(route);
  return routes.filter((entry) => {
    const values = [entry.slug, entry.suggested_site_path, entry.storyblok_slug]
      .map(normalizeRouteSelector);
    return values.includes(normalized);
  });
}

function normalizeRouteSelector(value) {
  return String(value || '')
    .trim()
    .replace(/^\/+|\/+$/g, '')
    .replace(/^home$/, '');
}

function normalizeSitePath(value) {
  const raw = String(value || '/').trim();
  if (!raw || raw === 'home') return '/';
  if (raw.startsWith('//') || /^[a-z][a-z0-9+.-]*:/i.test(raw)) return raw;
  const withoutQuery = raw.split('#')[0].split('?')[0];
  const withSlash = withoutQuery.startsWith('/') ? withoutQuery : `/${withoutQuery}`;
  const compact = withSlash.replace(/\/+/g, '/').replace(/\/$/g, '');
  return compact || '/';
}

function safeSitePath(sitePath) {
  return Boolean(sitePath) &&
    sitePath.startsWith('/') &&
    !sitePath.startsWith('//') &&
    !sitePath.includes('..') &&
    !/^[a-z][a-z0-9+.-]*:/i.test(sitePath);
}

function normalizeRelativePath(filePath) {
  return String(filePath || '').replaceAll('\\', '/').replace(/^\/+/, '');
}

function uniqueRouteEntries(routes) {
  const seen = new Set();
  return routes.filter((route) => {
    const key = `${route.file_path}:${route.exact_path}:${route.route_pattern}`;
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  }).sort((left, right) => left.file_path.localeCompare(right.file_path));
}

function escapeRegExp(value) {
  return String(value).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function emptyRouteCollisionSummary() {
  return {
    routes: 0,
    clear: 0,
    blocked: 0,
    warnings: 0,
    existing_route_files: 0,
    exact_route_file_collisions: 0,
    dynamic_route_overlaps: 0,
    rewrite_rules: 0,
    rewrite_overlaps: 0
  };
}
